// Bag and wishlist items store the collection name in the language they were
// added in, so an English title is mapped to its Thai one when it is shown.
export function localizeCollectionName(name, locale) {
  if (locale !== "th") return name;
  const slug = Object.keys(shopEn.collections).find((key) => shopEn.collections[key].title === name);
  return slug ? shopTh.collections[slug].title : name;
}
