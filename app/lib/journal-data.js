export function getJournalArticle(slug) {
  return journalArticles.find((article) => article.slug === slug) || null;
}

export function byLanguage(entry, language = "en") {
  if (!entry || typeof entry !== "object") {
    return "";
  }

  return entry[language] || entry.en || "";
}
