// ── language choice ─────────────────────────────────────────────────────────

export const ADMIN_LANGS = Object.freeze(["en", "th"]);
export const DEFAULT_ADMIN_LANG = "en";

// The language choice is remembered in a cookie that the browser script reads
// too, so it is deliberately not httpOnly. It only applies under /admin.
export const ADMIN_LANG_COOKIE = "maris_admin_lang";
export const ADMIN_LANG_COOKIE_PATH = "/admin";
export const ADMIN_LANG_COOKIE_MAX_AGE = 60 * 60 * 24 * 365;

const ADMIN_LOCALES = Object.freeze({ en: "en-GB", th: "th-TH" });

export function normalizeAdminLang(value) {
  const lang = String(value ?? "").trim().toLowerCase();
  return ADMIN_LANGS.includes(lang) ? lang : DEFAULT_ADMIN_LANG;
}

// The Set-Cookie / document.cookie string that stores the choice.
export function buildAdminLangCookie(lang, { secure = false } = {}) {
  return [
    `${ADMIN_LANG_COOKIE}=${normalizeAdminLang(lang)}`,
    `Path=${ADMIN_LANG_COOKIE_PATH}`,
    `Max-Age=${ADMIN_LANG_COOKIE_MAX_AGE}`,
    "SameSite=Lax",
    ...(secure ? ["Secure"] : [])
  ].join("; ");
}

// BCP 47 locale for Intl: Thai uses th-TH (Buddhist-era dates); English keeps
// the en-GB format the admin has always used.
export function getAdminLocale(lang) {
  return ADMIN_LOCALES[normalizeAdminLang(lang)];
}

// ── translation ─────────────────────────────────────────────────────────────

const DICTIONARIES = { en, th };
const hasOwn = (object, key) => Object.prototype.hasOwnProperty.call(object, key);

function interpolate(template, vars) {
  return String(template).replace(/\{(\w+)\}/g, (match, name) => (
    vars && vars[name] !== undefined && vars[name] !== null ? String(vars[name]) : match
  ));
}

export function getAdminMessages(lang) {
  return DICTIONARIES[normalizeAdminLang(lang)];
}

// t(key, vars) replaces {name} placeholders. tp(key, n, vars) picks key.one when
// n is 1 and key.other otherwise (Thai has no plural; both entries match).
// A key that is missing is shown as itself, so a gap is visible, not blank.
// ADMIN_I18N_CLIENT_HELPER below must keep exactly these rules.
export function createAdminT(lang) {
  const activeLang = normalizeAdminLang(lang);
  const messages = DICTIONARIES[activeLang];
  const t = (key, vars) => interpolate(hasOwn(messages, key) ? messages[key] : key, vars);
  t.has = (key) => hasOwn(messages, key);
  const tp = (key, n, vars) => t(`${key}${Number(n) === 1 ? ".one" : ".other"}`, { n, ...(vars || {}) });
  t.plural = tp;

  return { t, tp, lang: activeLang, locale: getAdminLocale(activeLang) };
}

// ── what the browser scripts receive ────────────────────────────────────────

// Keys only the server-rendered markup uses stay out of the inline dictionary.
const SERVER_ONLY_PREFIXES = Object.freeze([
  "login.", "setup.", "page.", "role.", "nav.", "lang.",
  "dash.", "bs.", "inv.", "cr.", "ws.", "inq.", "cust.", "news.", "set.", "sys.", "del."
]);

export function getAdminClientMessages(lang) {
  return Object.fromEntries(
    Object.entries(getAdminMessages(lang)).filter(([key]) => !SERVER_ONLY_PREFIXES.some((prefix) => key.startsWith(prefix)))
  );
}

// JSON that is safe to put inside an inline <script>.
export function toInlineJson(value) {
  const escape = (code) => "\\u" + code.toString(16).padStart(4, "0");
  return JSON.stringify(value)
    .replace(/[<>&]/g, (char) => escape(char.charCodeAt(0)))
    .replace(new RegExp(String.fromCharCode(0x2028) + "|" + String.fromCharCode(0x2029), "g"), (char) => escape(char.charCodeAt(0)));
}

// Runs in the browser after window.MARIS_ADMIN_I18N is set: defines t(key, vars),
// t.plural(key, n, vars) and the language switch used by every admin page.
export const ADMIN_I18N_CLIENT_HELPER = `(function (w) {
  var data = w.MARIS_ADMIN_I18N || {};
  var messages = data.messages || {};
  var own = Object.prototype.hasOwnProperty;
  function fill(template, vars) {
    return String(template).replace(/\\{(\\w+)\\}/g, function (match, name) {
      return vars && vars[name] !== undefined && vars[name] !== null ? String(vars[name]) : match;
    });
  }
  function t(key, vars) { return fill(own.call(messages, key) ? messages[key] : key, vars); }
  t.has = function (key) { return own.call(messages, key); };
  t.plural = function (key, n, vars) {
    var all = { n: n };
    if (vars) { for (var name in vars) { if (own.call(vars, name)) all[name] = vars[name]; } }
    return t(key + (Number(n) === 1 ? ".one" : ".other"), all);
  };
  w.marisAdminT = t;
  w.marisAdminSetLang = function (lang) {
    if (lang !== "th" && lang !== "en") return;
    var cookie = data.cookie || {};
    document.cookie = cookie.name + "=" + lang + "; Path=" + cookie.path + "; Max-Age=" + cookie.maxAge + "; SameSite=Lax" + (w.location.protocol === "https:" ? "; Secure" : "");
    w.location.reload();
  };
})(window);`;

// The inline script the server renders: the active language's dictionary (or
// only the language settings, for pages with no client text) plus the helper.
export function buildAdminI18nBootstrap(lang, { withMessages = true } = {}) {
  const activeLang = normalizeAdminLang(lang);
  const payload = {
    lang: activeLang,
    locale: getAdminLocale(activeLang),
    cookie: { name: ADMIN_LANG_COOKIE, path: ADMIN_LANG_COOKIE_PATH, maxAge: ADMIN_LANG_COOKIE_MAX_AGE },
    messages: withMessages ? getAdminClientMessages(activeLang) : {}
  };

  return `window.MARIS_ADMIN_I18N=${toInlineJson(payload)};${ADMIN_I18N_CLIENT_HELPER}`;
}
